/** Generate a checked function index from the repository's documented declaration conventions. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));

/** Read an immediately preceding block or line comment, excluding unrelated earlier statements. */
function precedingComment(source, offset) {
  const prefix = source.slice(0, offset).trimEnd();
  const block = prefix.match(/\/\*((?:(?!\/\*|\*\/)[\s\S])*)\*\/$/);
  if (block)
    return block[1]
      .replace(/^\s*\* ?/gm, "")
      .replace(/\s+/g, " ")
      .trim();
  const lines = prefix.match(/(?:^|\n)((?:\s*\/\/[^\n]*\n?)+)$/);
  return lines ? lines[1].replace(/\/\//g, "").replace(/\s+/g, " ").trim() : "";
}

/** Scan supported declaration forms; public object interfaces are indexed only in browser source. */
export function scanFunctions(source, includeInterfaces = false) {
  const patterns = [
    /^[ \t]*(?:(?:export\s+)?(?:async\s+)?function\s+([\w$]+)\s*\(|(?:const|let)\s+([\w$]+)\s*=\s*(?:async\s+)?\([^\n]*?\)\s*=>|(window\.[\w$]+)\s*=\s*(?:async\s+)?\([^\n]*?\)\s*=>)/gm,
  ];
  if (includeInterfaces)
    patterns.push(
      /^[ \t]*(?:((?:get|set)\s+[\w$]+)\([^\n]*?\)\s*\{|([\w$]+):\s*(?:async\s+)?\([^\n]*?\)\s*=>)/gm,
    );
  return patterns
    .flatMap((pattern) =>
      [...source.matchAll(pattern)].map((match) => ({
        name: match.slice(1).find(Boolean),
        comment: precedingComment(source, match.index),
        offset: match.index,
      })),
    )
    .sort((a, b) => a.offset - b.offset);
}

/** Index named helpers and public browser interfaces; anonymous callbacks belong to their enclosing feature or test. */
export function functionInventory() {
  const rows = [];
  for (const directory of ["src", "scripts", "tests"]) {
    const files = fs
      .readdirSync(path.join(root, directory), { recursive: true })
      .filter((file) => /\.(js|mjs|cjs)$/.test(file))
      .sort();
    for (const relative of files) {
      const file = directory + "/" + relative.replaceAll(path.sep, "/");
      const source = fs.readFileSync(path.join(root, file), "utf8");
      // This follows documented source formatting, not a general JavaScript grammar.
      for (const { name, comment } of scanFunctions(
        source,
        directory === "src",
      ))
        rows.push({ file, name, comment });
    }
  }
  return rows;
}

/** Render repeatable Markdown so code comments and developer reference cannot drift silently. */
export function functionDocument() {
  const rows = functionInventory();
  const missing = rows.filter((row) => !row.comment);
  if (missing.length)
    throw new Error(
      "Missing function comments: " +
        missing.map((row) => row.file + ":" + row.name).join(", "),
    );
  let text =
    "# Function reference / 函式索引\n\nGenerated by `node scripts/document-functions.mjs`. Regenerate after changing named functions or comments; `--check` rejects drift. / 修改具名函式或註解後重新產生，本文件由檢查防止與程式不一致。\n\nThis index covers named functions and directly assigned arrow helpers in src, scripts and tests, plus browser window factories, object arrow interfaces and getters/setters. Anonymous callbacks, module factory closures and test fixture methods are described by their enclosing feature or test. Keep declaration headers on their own line; this convention-based scanner is not a full JavaScript parser. / 索引涵蓋具名函式、直接指派的箭頭 helper，以及前端 window 工廠、物件箭頭介面和 getter/setter；匿名回呼、模組工廠閉包及測試替身方法由所屬功能或測試說明。宣告標頭須獨立成行，不能以此掃描器取代完整語法分析。\n";
  for (const file of new Set(rows.map((row) => row.file))) {
    text += `\n## ${file}\n\n[Source / 原始碼](../${file})\n\n| Function / 函式 | Responsibility / 英文註解 |\n| --- | --- |\n`;
    for (const row of rows.filter((row) => row.file === file))
      text += `| \`${row.name}\` | ${row.comment.replaceAll("|", "\\|")} |\n`;
  }
  return text;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const file = path.join(root, "docs/function-reference.md"),
    expected = functionDocument();
  if (process.argv.includes("--check")) {
    if (
      !fs.existsSync(file) ||
      fs.readFileSync(file, "utf8").replaceAll("\r\n", "\n") !== expected
    )
      throw new Error(
        "Function documentation is stale. Run node scripts/document-functions.mjs.",
      );
    console.log("PASS function comments and reference match.");
  } else {
    fs.writeFileSync(file, expected);
    console.log("Updated docs/function-reference.md");
  }
}
